#!/usr/bin/env bash
# Builds native/libsqlite3.so from the same SQLite version and compile options that
# sqlite-jdbc 3.50.3.0 bundles (from `PRAGMA compile_options`), so FFM and JDBC run the same engine.
set -euo pipefail
cd "$(dirname "$0")/.."
VER=3500300
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
curl -fsSL -o "$WORK/src.zip" "https://www.sqlite.org/2025/sqlite-amalgamation-${VER}.zip"
unzip -q "$WORK/src.zip" -d "$WORK"
mkdir -p native
gcc -O2 -fPIC -shared -o native/libsqlite3.so "$WORK/sqlite-amalgamation-${VER}/sqlite3.c" \
  -DSQLITE_THREADSAFE=1 -DSQLITE_DEFAULT_MEMSTATUS=0 -DSQLITE_TEMP_STORE=1 \
  -DSQLITE_DEFAULT_AUTOVACUUM=0 -DSQLITE_DEFAULT_RECURSIVE_TRIGGERS=1 -DSQLITE_DEFAULT_PCACHE_INITSZ=20 \
  -DSQLITE_DEFAULT_WORKER_THREADS=0 -DSQLITE_MAX_WORKER_THREADS=8 -DSQLITE_DIRECT_OVERFLOW_READ \
  -DSQLITE_DISABLE_PAGECACHE_OVERFLOW_STATS -DSQLITE_ENABLE_COLUMN_METADATA -DSQLITE_ENABLE_DBSTAT_VTAB \
  -DSQLITE_ENABLE_FTS3 -DSQLITE_ENABLE_FTS3_PARENTHESIS -DSQLITE_ENABLE_FTS5 -DSQLITE_ENABLE_LOAD_EXTENSION \
  -DSQLITE_ENABLE_MATH_FUNCTIONS -DSQLITE_ENABLE_RTREE -DSQLITE_ENABLE_STAT4 -DSQLITE_HAVE_ISNAN \
  -DSQLITE_MAX_ATTACHED=125 -DSQLITE_MAX_COLUMN=32767 -DSQLITE_MAX_LENGTH=2147483647 \
  -DSQLITE_MAX_MMAP_SIZE=1099511627776 -DSQLITE_MAX_PAGE_COUNT=4294967294 -DSQLITE_MAX_SQL_LENGTH=1073741824 \
  -DSQLITE_MAX_VARIABLE_NUMBER=250000 -DSQLITE_MAX_DEFAULT_PAGE_SIZE=8192 -DSQLITE_MALLOC_SOFT_LIMIT=1024 \
  -DHAVE_USLEEP=1 -lpthread -lm -ldl
echo "built $(pwd)/native/libsqlite3.so"
