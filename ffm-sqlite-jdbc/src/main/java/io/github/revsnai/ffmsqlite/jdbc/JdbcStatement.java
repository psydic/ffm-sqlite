package io.github.revsnai.ffmsqlite.jdbc;

import io.github.revsnai.ffmsqlite.db.SQLiteException;

import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.sql.Types;
import java.time.Duration;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;

/** {@code java.sql.Statement} over an ffm-sqlite statement. Every call except {@link #cancel} synchronizes on the connection. */
class JdbcStatement implements Statement {
    final JdbcConnection conn;
    private final io.github.revsnai.ffmsqlite.db.Statement st; // null for PreparedStatement
    JdbcResultSet current;
    long updateCount = -1;
    boolean closed;
    long maxRows;
    int queryTimeoutSeconds;
    private int fetchSize;
    private int maxFieldSize;
    private boolean closeOnCompletion;
    private boolean poolable;
    private final List<String> batch = new ArrayList<>();
    boolean hasGeneratedKey;
    private long generatedKey;

    JdbcStatement(JdbcConnection conn, io.github.revsnai.ffmsqlite.db.Statement st) {
        this.conn = conn;
        this.st = st;
        this.poolable = st == null;
    }

    void checkOpen() throws SQLException {
        if (closed) {
            throw Errors.closed("Statement");
        }
        conn.checkOpen();
    }

    void closeCurrent() {
        if (current != null) {
            current.closeQuietly();
            current = null;
        }
    }

    /** Called when the current result set is closed by the user. */
    void resultSetClosed(JdbcResultSet rs) throws SQLException {
        if (rs == current) {
            current = null;
            if (closeOnCompletion) {
                close();
            }
        }
    }

    /** INSERT or REPLACE (also after a WITH clause): a statement whose rowid getGeneratedKeys() reports. */
    static boolean isInsert(String sql) {
        String s = sql.stripLeading();
        while (s.startsWith("--") || s.startsWith("/*")) {
            int end = s.startsWith("--") ? s.indexOf('\n') : s.indexOf("*/") + 1;
            s = end <= 0 ? "" : s.substring(end + 1).stripLeading();
        }
        String head = s.length() > 7 ? s.substring(0, 7).toUpperCase(Locale.ROOT) : s.toUpperCase(Locale.ROOT);
        return head.startsWith("INSERT") || head.startsWith("REPLACE")
                || (head.startsWith("WITH") && s.toUpperCase(Locale.ROOT).contains("INSERT"));
    }

    /** last_insert_rowid() before a statement runs, for {@link #captureKey}. */
    long rowidBefore() throws SQLiteException {
        return conn.db.getLastInsertRowId();
    }

    /**
     * Records last_insert_rowid() after an INSERT, for getGeneratedKeys(). An upsert that took its DO UPDATE path
     * changed a row without inserting one, leaving last_insert_rowid() at some earlier insert (maybe into another
     * table): an unchanged rowid after an ON CONFLICT statement therefore means no key.
     */
    void captureKey(String sql, long changes, boolean requested, long rowidBefore) throws SQLException {
        hasGeneratedKey = false;
        if ((requested || conn.config.generatedKeys) && changes > 0 && isInsert(sql)) {
            try {
                long rowid = conn.db.getLastInsertRowId();
                if (rowid == rowidBefore && sql.toUpperCase(Locale.ROOT).contains("ON CONFLICT")) {
                    return;
                }
                generatedKey = rowid;
                hasGeneratedKey = true;
            } catch (SQLiteException e) {
                throw Errors.of(e);
            }
        }
    }

    // ------------------------------------------------------------------ execution

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        synchronized (conn) {
            checkOpen();
            closeCurrent();
            try {
                applyTimeout();
                current = new JdbcResultSet(this, conn, st.executeQuery(sql), maxRows);
                updateCount = -1;
                return current;
            } catch (SQLiteException e) {
                throw Errors.of(e);
            }
        }
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return (int) update(sql, false);
    }

    @Override
    public long executeLargeUpdate(String sql) throws SQLException {
        return update(sql, false);
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return (int) update(sql, autoGeneratedKeys == RETURN_GENERATED_KEYS);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return (int) update(sql, true);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return (int) update(sql, true);
    }

    @Override
    public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return update(sql, autoGeneratedKeys == RETURN_GENERATED_KEYS);
    }

    @Override
    public long executeLargeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return update(sql, true);
    }

    @Override
    public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
        return update(sql, true);
    }

    private long update(String sql, boolean keys) throws SQLException {
        synchronized (conn) {
            checkOpen();
            closeCurrent();
            try {
                applyTimeout();
                long before = rowidBefore();
                long n = st.executeLargeUpdate(sql);
                captureKey(sql, n, keys, before);
                updateCount = n;
                return n;
            } catch (SQLiteException e) {
                throw Errors.of(e);
            }
        }
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        return execute(sql, false);
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return execute(sql, autoGeneratedKeys == RETURN_GENERATED_KEYS);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return execute(sql, true);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return execute(sql, true);
    }

    private boolean execute(String sql, boolean keys) throws SQLException {
        synchronized (conn) {
            checkOpen();
            closeCurrent();
            try {
                applyTimeout();
                long before = rowidBefore();
                if (st.execute(sql)) {
                    current = new JdbcResultSet(this, conn, st.getResultSet(), maxRows);
                    updateCount = -1;
                    return true;
                }
                updateCount = st.getUpdateCount();
                captureKey(sql, updateCount, keys, before);
                return false;
            } catch (SQLiteException e) {
                throw Errors.of(e);
            }
        }
    }

    private void applyTimeout() throws SQLiteException {
        if (st != null) {
            st.setQueryTimeout(Duration.ofSeconds(queryTimeoutSeconds));
        }
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        synchronized (conn) {
            checkOpen();
            return current;
        }
    }

    @Override
    public int getUpdateCount() throws SQLException {
        synchronized (conn) {
            checkOpen();
            return (int) updateCount;
        }
    }

    @Override
    public long getLargeUpdateCount() throws SQLException {
        synchronized (conn) {
            checkOpen();
            return updateCount;
        }
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        return getMoreResults(CLOSE_CURRENT_RESULT);
    }

    @Override
    public boolean getMoreResults(int currentHandling) throws SQLException {
        synchronized (conn) {
            checkOpen();
            if (currentHandling != KEEP_CURRENT_RESULT) {
                closeCurrent();
            } else {
                current = null;
            }
            updateCount = -1;
            return false;
        }
    }

    /** The rowid of the row inserted by the last INSERT, in a column named {@code last_insert_rowid()} as in sqlite-jdbc. */
    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        synchronized (conn) {
            checkOpen();
            List<Object[]> rows = hasGeneratedKey ? List.<Object[]>of(new Object[]{generatedKey}) : List.of();
            return new MemoryResultSet(this, conn.config, new String[]{"last_insert_rowid()"}, new int[]{Types.BIGINT}, rows);
        }
    }

    // ------------------------------------------------------------------ batches

    @Override
    public void addBatch(String sql) throws SQLException {
        synchronized (conn) {
            checkOpen();
            batch.add(sql);
        }
    }

    @Override
    public void clearBatch() throws SQLException {
        synchronized (conn) {
            checkOpen();
            batch.clear();
        }
    }

    @Override
    public int[] executeBatch() throws SQLException {
        long[] counts = executeLargeBatch();
        int[] out = new int[counts.length];
        for (int i = 0; i < counts.length; i++) {
            out[i] = (int) counts[i];
        }
        return out;
    }

    @Override
    public long[] executeLargeBatch() throws SQLException {
        synchronized (conn) {
            checkOpen();
            closeCurrent();
            long[] counts = new long[batch.size()];
            try {
                for (int i = 0; i < counts.length; i++) {
                    try {
                        counts[i] = st.executeLargeUpdate(batch.get(i));
                    } catch (SQLiteException e) {
                        SQLException cause = Errors.of(e);
                        throw new BatchUpdateException(e.getMessage(), cause.getSQLState(), cause.getErrorCode(),
                                Arrays.copyOf(counts, i), cause);
                    }
                }
                return counts;
            } finally {
                batch.clear();
            }
        }
    }

    // ------------------------------------------------------------------ settings

    @Override
    public int getMaxFieldSize() throws SQLException {
        checkOpen();
        return maxFieldSize;
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        checkOpen();
        if (max < 0) {
            throw new SQLException("max field size must be >= 0", "HY024");
        }
        maxFieldSize = max; // accepted, not enforced (as in sqlite-jdbc)
    }

    @Override
    public int getMaxRows() throws SQLException {
        checkOpen();
        return (int) maxRows;
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        setLargeMaxRows(max);
    }

    @Override
    public long getLargeMaxRows() throws SQLException {
        checkOpen();
        return maxRows;
    }

    @Override
    public void setLargeMaxRows(long max) throws SQLException {
        checkOpen();
        if (max < 0) {
            throw new SQLException("max rows must be >= 0", "HY024");
        }
        maxRows = max;
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        checkOpen(); // SQLite has no JDBC escape syntax processing; accepted for compatibility
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        checkOpen();
        return queryTimeoutSeconds;
    }

    /** A real timeout: running statements are interrupted with {@code SQLTimeoutException} (sqlite-jdbc only bounds lock waits). */
    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        checkOpen();
        if (seconds < 0) {
            throw new SQLException("query timeout must be >= 0", "HY024");
        }
        queryTimeoutSeconds = seconds;
    }

    /** Lock-free on purpose: interrupts the statement running on this connection from another thread. */
    @Override
    public void cancel() throws SQLException {
        if (!closed && !conn.isClosed()) {
            if (st != null) {
                st.cancel();
            } else {
                ((JdbcPreparedStatement) this).ps.cancel();
            }
        }
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        checkOpen();
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public void setCursorName(String name) throws SQLException {
        checkOpen(); // no positioned updates in SQLite; ignored, as in sqlite-jdbc
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        checkOpen();
        if (direction != ResultSet.FETCH_FORWARD) {
            throw Errors.forwardOnly();
        }
    }

    @Override
    public int getFetchDirection() throws SQLException {
        checkOpen();
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        checkOpen();
        if (rows < 0) {
            throw new SQLException("fetch size must be >= 0", "HY024");
        }
        fetchSize = rows;
    }

    @Override
    public int getFetchSize() throws SQLException {
        checkOpen();
        return fetchSize;
    }

    @Override
    public int getResultSetConcurrency() throws SQLException {
        checkOpen();
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetType() throws SQLException {
        checkOpen();
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetHoldability() throws SQLException {
        checkOpen();
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public Connection getConnection() throws SQLException {
        checkOpen();
        return conn;
    }

    @Override
    public void close() throws SQLException {
        synchronized (conn) {
            if (closed) {
                return;
            }
            closed = true;
            closeCurrent();
            closeUnderlying();
        }
    }

    void closeUnderlying() {
        if (st != null) {
            st.close();
        }
    }

    @Override
    public boolean isClosed() {
        return closed || conn.isClosed();
    }

    @Override
    public void setPoolable(boolean poolable) throws SQLException {
        checkOpen();
        this.poolable = poolable;
    }

    @Override
    public boolean isPoolable() throws SQLException {
        checkOpen();
        return poolable;
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        checkOpen();
        closeOnCompletion = true;
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        checkOpen();
        return closeOnCompletion;
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        if (st != null && iface.isInstance(st)) {
            return iface.cast(st);
        }
        throw new SQLException("not a wrapper for " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this) || (st != null && iface.isInstance(st));
    }
}
