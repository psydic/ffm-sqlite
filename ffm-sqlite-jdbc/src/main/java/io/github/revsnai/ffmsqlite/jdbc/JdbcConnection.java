package io.github.revsnai.ffmsqlite.jdbc;

import io.github.revsnai.ffmsqlite.db.SQLite;
import io.github.revsnai.ffmsqlite.db.SQLiteException;

import java.sql.Array;
import java.sql.Blob;
import java.sql.CallableStatement;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.NClob;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.SQLXML;
import java.sql.Savepoint;
import java.sql.Statement;
import java.sql.Struct;
import java.util.HashMap;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * {@code java.sql.Connection} over an {@link io.github.revsnai.ffmsqlite.db.Connection}.
 *
 * <p>Thread-safe like sqlite-jdbc: every call on this connection, and on its statements and result sets,
 * synchronizes on this object, so sharing one connection between threads serializes access instead of being
 * undefined behaviour. {@code Statement.cancel()} is the exception: it is lock-free so it can interrupt a running
 * statement from another thread.
 *
 * <p>{@code unwrap(io.github.revsnai.ffmsqlite.db.Connection.class)} gives the underlying connection for ffm-sqlite features
 * (user-defined functions, collations, hooks, backup, serialize); use it only while holding no JDBC objects
 * in other threads.
 */
final class JdbcConnection implements Connection {
    final io.github.revsnai.ffmsqlite.db.Connection db;
    final JdbcConfig config;
    final String url;
    private final Properties clientInfo = new Properties();
    private Map<String, Class<?>> typeMap = new HashMap<>();
    /** Set by {@link #abort}: the connection counts as closed at once, before the queued close() runs. */
    private volatile boolean aborted;
    /** Opened read-only, or with {@code query_only} on in the URL/properties: read-only whatever setReadOnly says. */
    private final boolean configuredReadOnly;
    private boolean readOnly;
    private int isolation = TRANSACTION_SERIALIZABLE;
    private int holdability = ResultSet.CLOSE_CURSORS_AT_COMMIT;
    private int savepointCounter;
    private int networkTimeout;

    JdbcConnection(String url, JdbcConfig config) throws SQLException {
        this.url = url;
        this.config = config;
        try {
            this.db = SQLite.getConnection(config.path, config.sqlite);
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
        String queryOnly = config.sqlite.pragmas().get("query_only");
        this.configuredReadOnly = config.sqlite.readOnly()
                || (queryOnly != null && (queryOnly.equalsIgnoreCase("ON") || queryOnly.equals("1")));
        this.readOnly = configuredReadOnly;
    }

    void checkOpen() throws SQLException {
        if (aborted || db.isClosed()) {
            throw Errors.closed("Connection");
        }
    }

    /** Runs internal SQL (PRAGMA, SAVEPOINT); callers hold the lock. */
    private void run(String sql) throws SQLException {
        try (io.github.revsnai.ffmsqlite.db.Statement st = db.createStatement()) {
            st.executeUpdate(sql);
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    // ------------------------------------------------------------------ statements

    @Override
    public synchronized Statement createStatement() throws SQLException {
        checkOpen();
        try {
            return new JdbcStatement(this, db.createStatement());
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    @Override
    public synchronized Statement createStatement(int type, int concurrency) throws SQLException {
        checkResultSetType(type, concurrency);
        return createStatement();
    }

    @Override
    public synchronized Statement createStatement(int type, int concurrency, int holdability) throws SQLException {
        checkResultSetType(type, concurrency);
        return createStatement();
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql) throws SQLException {
        return prepare(sql, false);
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return prepare(sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS);
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        return prepare(sql, true);
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        return prepare(sql, true);
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException {
        checkResultSetType(type, concurrency);
        return prepare(sql, false);
    }

    @Override
    public synchronized PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability) throws SQLException {
        checkResultSetType(type, concurrency);
        return prepare(sql, false);
    }

    private PreparedStatement prepare(String sql, boolean keys) throws SQLException {
        checkOpen();
        try {
            return new JdbcPreparedStatement(this, db.prepareStatement(sql), sql, keys);
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    private static void checkResultSetType(int type, int concurrency) throws SQLException {
        if (type != ResultSet.TYPE_FORWARD_ONLY || concurrency != ResultSet.CONCUR_READ_ONLY) {
            throw Errors.unsupported("result set type " + type + " / concurrency " + concurrency
                    + " (only TYPE_FORWARD_ONLY, CONCUR_READ_ONLY)");
        }
    }

    @Override
    public CallableStatement prepareCall(String sql) throws SQLException {
        throw Errors.unsupported("CallableStatement (SQLite has no stored procedures)");
    }

    @Override
    public CallableStatement prepareCall(String sql, int type, int concurrency) throws SQLException {
        throw Errors.unsupported("CallableStatement (SQLite has no stored procedures)");
    }

    @Override
    public CallableStatement prepareCall(String sql, int type, int concurrency, int holdability) throws SQLException {
        throw Errors.unsupported("CallableStatement (SQLite has no stored procedures)");
    }

    @Override
    public String nativeSQL(String sql) {
        return sql;
    }

    // ------------------------------------------------------------------ transactions

    @Override
    public synchronized void setAutoCommit(boolean autoCommit) throws SQLException {
        checkOpen();
        try {
            db.setAutoCommit(autoCommit);
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    @Override
    public synchronized boolean getAutoCommit() throws SQLException {
        checkOpen();
        try {
            return db.getAutoCommit();
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    @Override
    public synchronized void commit() throws SQLException {
        checkOpen();
        try {
            db.commit();
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    @Override
    public synchronized void rollback() throws SQLException {
        checkOpen();
        try {
            db.rollback();
        } catch (SQLiteException e) {
            throw Errors.of(e);
        }
    }

    @Override
    public synchronized Savepoint setSavepoint() throws SQLException {
        return savepoint(new JdbcSavepoint(++savepointCounter, null));
    }

    @Override
    public synchronized Savepoint setSavepoint(String name) throws SQLException {
        return savepoint(new JdbcSavepoint(0, name));
    }

    private Savepoint savepoint(JdbcSavepoint sp) throws SQLException {
        checkOpen();
        if (getAutoCommit()) {
            throw new SQLException("cannot set a savepoint in auto-commit mode", "3B001");
        }
        run("SAVEPOINT " + sp.sqlName());
        return sp;
    }

    @Override
    public synchronized void rollback(Savepoint savepoint) throws SQLException {
        checkOpen();
        run("ROLLBACK TO SAVEPOINT " + JdbcSavepoint.of(savepoint).sqlName());
    }

    @Override
    public synchronized void releaseSavepoint(Savepoint savepoint) throws SQLException {
        checkOpen();
        run("RELEASE SAVEPOINT " + JdbcSavepoint.of(savepoint).sqlName());
    }

    /**
     * SERIALIZABLE (SQLite's normal behaviour) or READ_UNCOMMITTED ({@code PRAGMA read_uncommitted}, effective with
     * a shared cache). READ_COMMITTED and REPEATABLE_READ are upgraded to SERIALIZABLE, as JDBC permits.
     */
    @Override
    public synchronized void setTransactionIsolation(int level) throws SQLException {
        checkOpen();
        switch (level) {
            case TRANSACTION_READ_UNCOMMITTED -> run("PRAGMA read_uncommitted = 1");
            case TRANSACTION_READ_COMMITTED, TRANSACTION_REPEATABLE_READ, TRANSACTION_SERIALIZABLE -> {
                run("PRAGMA read_uncommitted = 0");
                level = TRANSACTION_SERIALIZABLE;
            }
            default -> throw new SQLException("unsupported transaction isolation level " + level, "HY024");
        }
        isolation = level;
    }

    @Override
    public synchronized int getTransactionIsolation() throws SQLException {
        checkOpen();
        return isolation;
    }

    // ------------------------------------------------------------------ connection state

    @Override
    public synchronized void close() {
        db.close();
    }

    @Override
    public boolean isClosed() {
        return aborted || db.isClosed();
    }

    @Override
    public synchronized DatabaseMetaData getMetaData() throws SQLException {
        checkOpen();
        return new JdbcDatabaseMetaData(this);
    }

    /**
     * {@code PRAGMA query_only}: rejects writes on this connection. A connection configured read-only (the
     * {@code readonly} open flag, or {@code query_only=true} in the URL/properties) stays read-only:
     * {@code setReadOnly(false)} is then ignored, as JDBC allows for this hint. Frameworks call it after every
     * read-only transaction (Spring does so unconditionally), which must not make a reader pool writable.
     */
    @Override
    public synchronized void setReadOnly(boolean readOnly) throws SQLException {
        checkOpen();
        boolean effective = readOnly || configuredReadOnly;
        if (effective != this.readOnly && !config.sqlite.readOnly()) {
            run("PRAGMA query_only = " + (effective ? 1 : 0));
        }
        this.readOnly = effective;
    }

    @Override
    public synchronized boolean isReadOnly() throws SQLException {
        checkOpen();
        return readOnly;
    }

    @Override
    public void setCatalog(String catalog) {
        // SQLite has no catalogs; JDBC says to ignore silently
    }

    @Override
    public String getCatalog() {
        return null;
    }

    @Override
    public void setSchema(String schema) {
        // ignored: SQLite resolves unqualified names itself (temp, then main, then attached)
    }

    @Override
    public String getSchema() {
        return null;
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        checkOpen();
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public synchronized Map<String, Class<?>> getTypeMap() throws SQLException {
        checkOpen();
        return typeMap;
    }

    @Override
    public synchronized void setTypeMap(Map<String, Class<?>> map) throws SQLException {
        checkOpen();
        typeMap = map == null ? new HashMap<>() : map;
    }

    @Override
    public synchronized void setHoldability(int holdability) throws SQLException {
        checkOpen();
        if (holdability != ResultSet.CLOSE_CURSORS_AT_COMMIT && holdability != ResultSet.HOLD_CURSORS_OVER_COMMIT) {
            throw new SQLException("invalid holdability " + holdability, "HY092");
        }
        this.holdability = holdability;
    }

    @Override
    public synchronized int getHoldability() throws SQLException {
        checkOpen();
        return holdability;
    }

    @Override
    public synchronized boolean isValid(int timeout) throws SQLException {
        if (timeout < 0) {
            throw new SQLException("timeout must be >= 0", "HY092");
        }
        if (db.isClosed()) {
            return false;
        }
        try (io.github.revsnai.ffmsqlite.db.Statement st = db.createStatement(); io.github.revsnai.ffmsqlite.db.ResultSet rs = st.executeQuery("SELECT 1")) {
            return rs.next();
        } catch (SQLiteException e) {
            return false;
        }
    }

    @Override
    public void setClientInfo(String name, String value) throws SQLClientInfoException {
        if (value == null) {
            clientInfo.remove(name);
        } else {
            clientInfo.setProperty(name, value);
        }
    }

    @Override
    public void setClientInfo(Properties properties) throws SQLClientInfoException {
        clientInfo.clear();
        if (properties != null) {
            clientInfo.putAll(properties);
        }
    }

    @Override
    public String getClientInfo(String name) {
        return clientInfo.getProperty(name);
    }

    @Override
    public Properties getClientInfo() {
        Properties copy = new Properties();
        copy.putAll(clientInfo);
        return copy;
    }

    @Override
    public void abort(Executor executor) throws SQLException {
        if (executor == null) {
            throw new SQLException("executor must not be null", "HY009");
        }
        if (aborted || db.isClosed()) {
            return;
        }
        aborted = true;     // closed from the caller's point of view from now on
        db.interrupt();     // lock-free: stops a running statement, so the close below can take the lock
        executor.execute(this::close);
    }

    @Override
    public synchronized void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
        checkOpen();
        networkTimeout = milliseconds; // no network: stored for getNetworkTimeout only
    }

    @Override
    public synchronized int getNetworkTimeout() throws SQLException {
        checkOpen();
        return networkTimeout;
    }

    // ------------------------------------------------------------------ unsupported object factories

    @Override
    public Clob createClob() throws SQLException {
        throw Errors.unsupported("createClob (use setString)");
    }

    @Override
    public Blob createBlob() throws SQLException {
        throw Errors.unsupported("createBlob (use setBytes)");
    }

    @Override
    public NClob createNClob() throws SQLException {
        throw Errors.unsupported("createNClob");
    }

    @Override
    public SQLXML createSQLXML() throws SQLException {
        throw Errors.unsupported("SQLXML");
    }

    @Override
    public Array createArrayOf(String typeName, Object[] elements) throws SQLException {
        throw Errors.unsupported("SQL arrays");
    }

    @Override
    public Struct createStruct(String typeName, Object[] attributes) throws SQLException {
        throw Errors.unsupported("SQL structs");
    }

    // ------------------------------------------------------------------ wrapper

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        if (iface.isInstance(db)) {
            return iface.cast(db);
        }
        throw new SQLException("not a wrapper for " + iface.getName(), "HY000");
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this) || iface.isInstance(db);
    }
}
